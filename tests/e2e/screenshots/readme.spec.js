import { test } from "@playwright/test";
import { waitForMapIdle } from "../helpers/mapIdle.js";
import { expectDefaultTheme } from "../helpers/theme.js";

/**
 * README hero screenshot — `./HERO.jpg` (repo root).
 *
 * One 1280×720 hero image of the app with the Info panel open over a live map,
 * rendered in the app's single default theme.
 *
 * This hero is DELIBERATELY NON-DETERMINISTIC: it is a genuine cold start
 * against `?country=random`, which fits the view to a different country every
 * run and renders live (un-stubbed) map tiles. That is the whole point — it is
 * marketing imagery showing the real app over real places, not a pixel
 * baseline.
 *
 * Consequently this spec must NOT import the shared E2E test fixture
 * (`../helpers/test.js`): that fixture installs the committed map-asset stubs,
 * which would pin the view to the demo area and defeat the random cold start.
 * It uses Playwright's base test directly.
 *
 * The file is a COMMITTED ARTEFACT regenerated by local full E2E runs (CI
 * excludes `@screenshots`; see `docs/13.ci.md`).
 */

test.setTimeout(120000);

// Live tiles: a stalled external request can delay map-idle past the wait.
test.describe.configure({ retries: 1 });

// Random-country cold start. The app's `?country=random` sentinel picks a
// random country and outranks any stored view, so the hero is different every
// run by design.
const HERO_URL = "/?country=random";

/**
 * Capture the hero composition: cold-start the app on a random country, wait
 * for the live map to settle and the Info panel to slide in, assert the default
 * theme, snapshot to the repo root.
 */
const captureHero = async (page, testInfo) => {
  // The hero shows the app as a returning user sees it: no onboarding hints.
  await page.addInitScript(() => {
    window.__ogisDisableHints = true;
  });
  await page.goto(HERO_URL);

  await waitForMapIdle(page, testInfo);
  await page.locator(".ogis-panel").waitFor({ state: "visible" });
  await expectDefaultTheme(page);
  // Let the offcanvas slide-in finish so the hero is not mid-transition.
  await page.waitForTimeout(400);

  console.log(`[README hero] captured ${page.url()}`);

  await page.screenshot({
    path: "HERO.jpg",
    type: "jpeg",
    quality: 80,
  });
};

test.describe("README hero", () => {
  test.use({ viewport: { width: 1280, height: 720 } });

  test("README hero @screenshots", async ({ page }, testInfo) => {
    await captureHero(page, testInfo);
  });
});
